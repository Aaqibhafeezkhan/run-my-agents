// Regenerates src/fonts.generated.ts from the Geist files in fonts/, so the board has its font with no network.
// Geist and Geist Mono are by Vercel, under the SIL Open Font License 1.1 (fonts/LICENSE-Geist.txt).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const b64 = (file: string) => readFileSync(join(root, "fonts", file)).toString("base64");
writeFileSync(
	join(root, "src", "fonts.generated.ts"),
	`// Generated by scripts/fonts.ts. Geist and Geist Mono by Vercel, SIL Open Font License 1.1.\nexport const GEIST = "${b64("Geist-Variable.woff2")}";\nexport const GEIST_MONO = "${b64("GeistMono-Variable.woff2")}";\n`,
);
console.log("fonts.generated.ts written");
